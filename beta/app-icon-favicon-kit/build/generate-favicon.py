#!/usr/bin/env python3
"""
Generate a dual-theme SVG favicon from light and dark SVG source icons.

The two sources should share identical geometry and have the same number/order
of fill="#RRGGBB" attributes. The script uses the light SVG as the geometry,
replaces its fill attributes with generated classes, then writes a <style> block
with light defaults and a dark-mode @media override.
"""

from __future__ import annotations

import os
import re
import sys
from pathlib import Path

SCRIPT_DIR = Path(__file__).resolve().parent
APP_ROOT = SCRIPT_DIR.parent

LIGHT = Path(os.environ.get("APP_ICON_LIGHT_SVG", APP_ROOT / "icon" / "app-icon-light.svg"))
DARK = Path(os.environ.get("APP_ICON_DARK_SVG", APP_ROOT / "icon" / "app-icon-dark.svg"))
OUT = Path(os.environ.get("APP_FAVICON_OUT", APP_ROOT / "favicon.svg"))

FILL_RE = re.compile(r'fill="(#[0-9A-Fa-f]{6})"')


def read(path: Path) -> str:
    if not path.exists():
        sys.exit(f"Error: missing source SVG: {path}")
    return path.read_text(encoding="utf-8")


def extract_fills(path: Path, text: str) -> list[str]:
    fills = FILL_RE.findall(text)
    if not fills:
        sys.exit(f"Error: {path.name} has no fill=\"#RRGGBB\" attributes.")
    return fills


def main() -> None:
    light_text = read(LIGHT)
    dark_text = read(DARK)
    light_fills = extract_fills(LIGHT, light_text)
    dark_fills = extract_fills(DARK, dark_text)

    if len(light_fills) != len(dark_fills):
        sys.exit(
            "Error: source SVG fill counts differ.\n"
            f"       {LIGHT.name}: {len(light_fills)} fills\n"
            f"       {DARK.name}: {len(dark_fills)} fills\n"
            "       Keep identical geometry and fill order for theme swapping."
        )

    classes = [f"favicon-fill-{idx}" for idx in range(len(light_fills))]
    index = 0

    def replace_fill(_match: re.Match[str]) -> str:
        nonlocal index
        cls = classes[index]
        index += 1
        return f'class="{cls}"'

    body = FILL_RE.sub(replace_fill, light_text)
    body = re.sub(r"<!DOCTYPE[^>]*>\s*", "", body, count=1)

    style_lines = ["  <style>"]
    for cls, color in zip(classes, light_fills):
        style_lines.append(f"    .{cls} {{ fill: {color}; }}")
    style_lines.append("    @media (prefers-color-scheme: dark) {")
    for cls, color in zip(classes, dark_fills):
        style_lines.append(f"      .{cls} {{ fill: {color}; }}")
    style_lines.append("    }")
    style_lines.append("  </style>")
    style = "\n".join(style_lines)

    body, count = re.subn(r"(<svg[^>]*>)", r"\1\n" + style, body, count=1)
    if count != 1:
        sys.exit("Error: could not locate opening <svg> tag.")

    header_comment = (
        "<!-- Generated by build/generate-favicon.py from the light/dark app "
        "icon SVGs. Do not edit by hand. -->"
    )
    body, count = re.subn(r"(<\?xml[^>]*\?>)", r"\1\n" + header_comment, body, count=1)
    if count != 1:
        body = header_comment + "\n" + body

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(body, encoding="utf-8")
    print(f"  {OUT.name:<32} generated (light + dark @media)")


if __name__ == "__main__":
    main()
