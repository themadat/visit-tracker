#!/usr/bin/env python3
"""
generate-favicon.py
-------------------
Combine icon/trail-log-light.svg and icon/trail-log-dark.svg into a single
favicon.svg at the repo root that swaps fills via @media (prefers-color-scheme).

The two source SVGs are expected to share identical geometry and differ only
in their fill colors. This script:

  1. Pulls the 5 fills (in document order) from each source.
  2. Replaces every fill="#RRGGBB" in the light SVG with a class="..." reference.
  3. Injects a <style> block with light defaults plus a dark-mode @media block.

The class names map to icon roles in fill order:
    bg, book, book-stroke, globe-ring, globe-core
"""

import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
LIGHT = REPO_ROOT / "icon" / "trail-log-light.svg"
DARK = REPO_ROOT / "icon" / "trail-log-dark.svg"
OUT = REPO_ROOT / "favicon.svg"

CLASSES = ["bg", "book", "book-stroke", "globe-ring", "globe-core"]
FILL_RE = re.compile(r'fill="(#[0-9A-Fa-f]{6})"')


def extract_fills(path: Path) -> list[str]:
    text = path.read_text()
    fills = FILL_RE.findall(text)
    if len(fills) != len(CLASSES):
        sys.exit(
            f"Error: {path.name} has {len(fills)} fills, expected {len(CLASSES)}.\n"
            f"       Update CLASSES in {Path(__file__).name} if the icon design changed."
        )
    return fills


def main() -> None:
    for svg in (LIGHT, DARK):
        if not svg.exists():
            sys.exit(f"Error: missing source SVG: {svg}")

    light_fills = extract_fills(LIGHT)
    dark_fills = extract_fills(DARK)

    text = LIGHT.read_text()

    # Replace fills in document order with class references.
    idx = [0]

    def sub(_match: re.Match[str]) -> str:
        cls = CLASSES[idx[0]]
        idx[0] += 1
        return f'class="{cls}"'

    body = FILL_RE.sub(sub, text)

    # Build the <style> block.
    style_lines = ["  <style>"]
    for cls, color in zip(CLASSES, light_fills):
        style_lines.append(f"    .{cls} {{ fill: {color}; }}")
    style_lines.append("    @media (prefers-color-scheme: dark) {")
    for cls, color in zip(CLASSES, dark_fills):
        style_lines.append(f"      .{cls} {{ fill: {color}; }}")
    style_lines.append("    }")
    style_lines.append("  </style>")
    style = "\n".join(style_lines)

    # Drop the SVG 1.1 DOCTYPE — modern browsers ignore it, and it interferes
    # with some SVG-as-favicon renderers.
    body = re.sub(r"<!DOCTYPE[^>]*>\s*", "", body, count=1)

    # Inject style block immediately after the opening <svg ...> tag.
    body, count = re.subn(r"(<svg[^>]*>)", r"\1\n" + style, body, count=1)
    if count != 1:
        sys.exit("Error: couldn't locate <svg> opening tag.")

    # The "generated by" note has to live AFTER the <?xml ...?> declaration,
    # not before it — the XML declaration must be the first thing in the file
    # or the SVG is technically invalid.
    header_comment = (
        "<!-- Generated by build/generate-favicon.py from "
        "icon/trail-log-{light,dark}.svg. Do not edit by hand. -->"
    )
    body, count = re.subn(
        r"(<\?xml[^>]*\?>)", r"\1\n" + header_comment, body, count=1
    )
    if count != 1:
        # No XML prolog present — prepend the comment in front of the SVG.
        body = header_comment + "\n" + body

    OUT.write_text(body)
    print("  favicon.svg                      generated (light + dark @media)")


if __name__ == "__main__":
    main()
